//! Fixed-point mixed-radix inverse MDCT and persistent TDAC, pinned `mdct.c`.
#![allow(
    clippy::cast_possible_truncation,
    clippy::cast_possible_wrap,
    clippy::cast_sign_loss
)]
// Fixed-width conversions follow the reference macros; transform sizes are mode bounded.
#[path = "transform_tables.rs"]
mod tables;
use tables::{FFT_TWIDDLES, MDCT_TWIDDLES960, WINDOW120};
pub(super) const fn window(index: usize) -> i16 {
    WINDOW120[index]
}
type Complex = (i32, i32);
const fn add(a: Complex, b: Complex) -> Complex {
    (a.0.wrapping_add(b.0), a.1.wrapping_add(b.1))
}
const fn sub(a: Complex, b: Complex) -> Complex {
    (a.0.wrapping_sub(b.0), a.1.wrapping_sub(b.1))
}
fn smul(a: i32, b: i16) -> i32 {
    ((i64::from(a) * i64::from(b)) >> 15) as i32
}
fn scale(a: Complex, b: i16) -> Complex {
    (smul(a.0, b), smul(a.1, b))
}
fn cmul(a: Complex, b: (i16, i16)) -> Complex {
    (
        smul(a.0, b.0).wrapping_sub(smul(a.1, b.1)),
        smul(a.1, b.0).wrapping_add(smul(a.0, b.1)),
    )
}
const fn round(x: i32, shift: u32) -> i32 {
    if shift == 0 {
        x
    } else {
        x.wrapping_add(1 << (shift - 1)) >> shift
    }
}
fn downshift(x: &mut [Complex], remaining: &mut u32, step: u32) {
    let shift = step.min(*remaining);
    *remaining -= shift;
    for value in x {
        if shift == 1 {
            value.0 >>= 1;
            value.1 >>= 1;
        } else if shift > 1 {
            value.0 = round(value.0, shift);
            value.1 = round(value.1, shift);
        }
    }
}

#[allow(clippy::too_many_lines)]
fn fft(x: &mut [Complex], shift: usize, mut down: u32) {
    let factors: &[(usize, usize)] = match shift {
        0 => &[(5, 96), (3, 32), (4, 8), (2, 4), (4, 1)],
        1 => &[(5, 48), (3, 16), (4, 4), (4, 1)],
        2 => &[(5, 24), (3, 8), (2, 4), (4, 1)],
        3 => &[(5, 12), (3, 4), (4, 1)],
        _ => unreachable!(),
    };
    let mut strides = vec![1];
    for &(radix, _) in factors {
        strides.push(strides.last().unwrap() * radix);
    }
    for stage in (0..factors.len()).rev() {
        let (radix, m) = factors[stage];
        let groups = strides[stage];
        let mm = if stage == 0 { 1 } else { factors[stage - 1].1 };
        let stride = groups << shift;
        downshift(
            x,
            &mut down,
            match radix {
                2 => 1,
                4 | 3 => 2,
                5 => 3,
                _ => unreachable!(),
            },
        );
        for group in 0..groups {
            if radix == 2 {
                let base = group * 8;
                let source = x[base + 4..base + 8].to_vec();
                let rotations = [
                    source[0],
                    (
                        smul(source[1].0.wrapping_add(source[1].1), 23_170),
                        smul(source[1].1.wrapping_sub(source[1].0), 23_170),
                    ),
                    (source[2].1, source[2].0.wrapping_neg()),
                    (
                        smul(source[3].1.wrapping_sub(source[3].0), 23_170),
                        smul(source[3].1.wrapping_add(source[3].0).wrapping_neg(), 23_170),
                    ),
                ];
                for j in 0..4 {
                    let a = x[base + j];
                    x[base + j] = add(a, rotations[j]);
                    x[base + 4 + j] = sub(a, rotations[j]);
                }
                continue;
            }
            for j in 0..m {
                let base = group * mm + j;
                let a = x[base];
                let mut v = [(0, 0); 5];
                v[0] = a;
                for k in 1..radix {
                    v[k] = if radix == 4 && m == 1 {
                        x[base + k * m]
                    } else {
                        cmul(x[base + k * m], FFT_TWIDDLES[k * j * stride])
                    };
                }
                match radix {
                    4 => {
                        let s5 = sub(a, v[2]);
                        let combined = add(a, v[2]);
                        let s3 = add(v[1], v[3]);
                        let s4 = sub(v[1], v[3]);
                        x[base] = add(combined, s3);
                        x[base + 2 * m] = sub(combined, s3);
                        x[base + m] = (s5.0.wrapping_add(s4.1), s5.1.wrapping_sub(s4.0));
                        x[base + 3 * m] = (s5.0.wrapping_sub(s4.1), s5.1.wrapping_add(s4.0));
                    }
                    3 => {
                        let s3 = add(v[1], v[2]);
                        let s0 = scale(sub(v[1], v[2]), -28_378);
                        let middle = (a.0.wrapping_sub(s3.0 >> 1), a.1.wrapping_sub(s3.1 >> 1));
                        x[base] = add(a, s3);
                        x[base + 2 * m] =
                            (middle.0.wrapping_add(s0.1), middle.1.wrapping_sub(s0.0));
                        x[base + m] = (middle.0.wrapping_sub(s0.1), middle.1.wrapping_add(s0.0));
                    }
                    5 => {
                        let s7 = add(v[1], v[4]);
                        let s10 = sub(v[1], v[4]);
                        let s8 = add(v[2], v[3]);
                        let s9 = sub(v[2], v[3]);
                        x[base] = add(a, add(s7, s8));
                        let s5 = add(a, add(scale(s7, 10_126), scale(s8, -26_510)));
                        let s6 = (
                            smul(s10.1, -31_164).wrapping_add(smul(s9.1, -19_261)),
                            smul(s10.0, -31_164)
                                .wrapping_add(smul(s9.0, -19_261))
                                .wrapping_neg(),
                        );
                        x[base + m] = sub(s5, s6);
                        x[base + 4 * m] = add(s5, s6);
                        let s11 = add(a, add(scale(s7, -26_510), scale(s8, 10_126)));
                        let s12 = (
                            smul(s9.1, -31_164).wrapping_sub(smul(s10.1, -19_261)),
                            smul(s10.0, -19_261).wrapping_sub(smul(s9.0, -31_164)),
                        );
                        x[base + 2 * m] = add(s11, s12);
                        x[base + 3 * m] = sub(s11, s12);
                    }
                    _ => unreachable!(),
                }
            }
        }
    }
    let remaining = down;
    downshift(x, &mut down, remaining);
}

/// Write one transform into an output buffer holding the preceding 60-sample tail.
fn backward(input: &[i32], offset: usize, stride: usize, shift: usize, out: &mut [i32]) {
    let n = 960 >> shift;
    let quarter = n / 2;
    let trig_start = match shift {
        0 => 0,
        1 => 960,
        2 => 1440,
        3 => 1680,
        _ => unreachable!(),
    };
    let trig = &MDCT_TWIDDLES960[trig_start..];
    let bitrev: &[usize] = match shift {
        0 => &tables::FFT_BITREV480,
        1 => &tables::FFT_BITREV240,
        2 => &tables::FFT_BITREV120,
        3 => &tables::FFT_BITREV60,
        _ => unreachable!(),
    };
    let max = input
        .iter()
        .skip(offset)
        .step_by(stride)
        .take(n)
        .map(|&x| x.abs())
        .max()
        .unwrap_or(0);
    let sum = input
        .iter()
        .skip(offset)
        .step_by(stride)
        .take(n)
        .fold(n as i32, |s, &x| s.wrapping_add((x >> 11).abs()));
    let pre = 0.max(29 - (31 - (1 + max).leading_zeros()) as i32) as u32;
    let post = (0.max(19 - (31 - sum.abs().leading_zeros()) as i32) as u32).min(pre);
    let mut data = vec![(0, 0); quarter];
    for i in 0..quarter {
        let x1 = input[offset + 2 * i * stride].wrapping_shl(pre);
        let x2 = input[offset + (n - 1 - 2 * i) * stride].wrapping_shl(pre);
        let yr = smul(x2, trig[i]).wrapping_add(smul(x1, trig[quarter + i]));
        let yi = smul(x1, trig[i]).wrapping_sub(smul(x2, trig[quarter + i]));
        data[bitrev[i]] = (yi, yr);
    }
    fft(&mut data, shift, pre - post);
    for (i, &value) in data.iter().enumerate() {
        out[60 + 2 * i] = value.0;
        out[60 + 2 * i + 1] = value.1;
    }
    for i in 0..quarter.div_ceil(2) {
        let left = 60 + 2 * i;
        let right = 60 + n - 2 - 2 * i;
        let (re, im) = (out[left + 1], out[left]);
        let yr = round(
            smul(re, trig[i]).wrapping_add(smul(im, trig[quarter + i])),
            post,
        );
        let yi = round(
            smul(re, trig[quarter + i]).wrapping_sub(smul(im, trig[i])),
            post,
        );
        let (re2, im2) = (out[right + 1], out[right]);
        out[left] = yr;
        out[right + 1] = yi;
        let yr = round(
            smul(re2, trig[quarter - i - 1]).wrapping_add(smul(im2, trig[n - i - 1])),
            post,
        );
        let yi = round(
            smul(re2, trig[n - i - 1]).wrapping_sub(smul(im2, trig[quarter - i - 1])),
            post,
        );
        out[right] = yr;
        out[left + 1] = yi;
    }
    for i in 0..60 {
        let x1 = out[119 - i];
        let x2 = out[i];
        out[i] = smul(x2, WINDOW120[119 - i]).wrapping_sub(smul(x1, WINDOW120[i]));
        out[119 - i] = smul(x2, WINDOW120[i]).wrapping_add(smul(x1, WINDOW120[119 - i]));
    }
}

pub(super) fn synthesize(input: &[i32], transient: bool, tail: &mut Vec<i32>) -> Vec<i32> {
    let n = input.len();
    let lm = (n / 120).ilog2() as usize;
    let blocks = if transient { 1 << lm } else { 1 };
    let shift = if transient { 3 } else { 3 - lm };
    let width = n / blocks;
    let mut output = vec![0; n + 60];
    if tail.len() == 60 {
        output[..60].copy_from_slice(tail);
    }
    for b in 0..blocks {
        backward(input, b, blocks, shift, &mut output[b * width..]);
    }
    tail.clear();
    tail.extend_from_slice(&output[n..n + 60]);
    output.truncate(n);
    output
}

