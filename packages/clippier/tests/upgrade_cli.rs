#[test]
fn selectors_and_config_overrides_are_forwarded() {
    let fixture = Fixture::new(Some("1.0.0"));
    fs::write(
        fixture.path().join("custom.toml"),
        "[upgrade]\npolicy = 'INCOMPATIBLE'\nlockfile = 'RESOLVE'\n",
    )
    .unwrap();
    let output = fixture.run(&[
        "plan",
        "--config",
        "custom.toml",
        "--compatible",
        "--no-lockfile",
        "--offline",
        "--dependency",
        "demo",
        "--package",
        "upgrade_cli_fixture",
        "--kinds",
        "normal",
        "--output",
        "json",
        "--diff",
    ]);
    assert!(output.status.success(), "{output:?}");
    let summary = report(&output);
    assert!(summary["diff"].as_str().unwrap().contains("1.2.0"));
    assert!(!summary["diff"].as_str().unwrap().contains("2.0.0"));
    assert_eq!(summary["report"]["lockfile"], "DISABLED");
    assert_eq!(summary["scope"], "PLAN");
    assert_eq!(summary["report"]["config"]["lockfile"], "NONE");
    assert_eq!(summary["report"]["config"]["policy"], "COMPATIBLE");
    assert_eq!(summary["report"]["config"]["registry"]["offline"], true);
    assert_eq!(summary["report"]["lockfile_only"], false);
    assert_eq!(summary["cli_overrides"]["lockfile_policy"], "NONE");
    assert_eq!(summary["cli_overrides"]["policy"], "COMPATIBLE");
    assert_eq!(summary["cli_overrides"]["offline"], true);
    let excluded = fixture.run(&[
        "plan",
        "--offline",
        "--no-lockfile",
        "--exclude",
        "demo",
        "--output",
        "json",
    ]);
    assert!(excluded.status.success(), "{excluded:?}");
    assert_eq!(report(&excluded)["outcome"], "UNCHANGED");
    fixture.assert_unchanged();
}

