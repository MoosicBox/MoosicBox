#![cfg(feature = "upgrade")]

use std::{
    fs,
    path::Path,
    process::{Command, Output, Stdio},
};

use serde_json::Value;
use sha2::{Digest, Sha256};

fn checksum(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .fold(String::new(), |mut output, byte| {
            use std::fmt::Write;
            write!(output, "{byte:02x}").unwrap();
            output
        })
}

fn cached_crate(cargo_home: &Path, version: &str) -> String {
    let encoder = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::default());
    let mut archive = tar::Builder::new(encoder);
    for (name, contents) in [
        (
            "Cargo.toml",
            format!("[package]\nname = 'demo'\nversion = '{version}'\nedition = '2021'\n"),
        ),
        ("src/lib.rs", String::new()),
    ] {
        let mut header = tar::Header::new_gnu();
        header.set_size(u64::try_from(contents.len()).unwrap());
        header.set_mode(0o644);
        header.set_cksum();
        archive
            .append_data(
                &mut header,
                format!("demo-{version}/{name}"),
                contents.as_bytes(),
            )
            .unwrap();
    }
    let bytes = archive.into_inner().unwrap().finish().unwrap();
    let checksum = checksum(&bytes);
    let cache = cargo_home.join("registry/cache/index.crates.io-1949cf8c6b5b557f");
    fs::create_dir_all(&cache).unwrap();
    fs::write(cache.join(format!("demo-{version}.crate")), bytes).unwrap();
    checksum
}

struct Fixture {
    root: tempfile::TempDir,
    original: String,
}

impl Fixture {
    fn new(requirement: Option<&str>) -> Self {
        let root = tempfile::tempdir().unwrap();
        let original = format!(
            "[package]\nname = 'upgrade_cli_fixture'\nversion = '0.1.0'\nedition = '2021'\n[workspace]\n{}",
            requirement.map_or_else(String::new, |requirement| format!(
                "[dependencies]\ndemo = '{requirement}'\n"
            ))
        );
        fs::write(root.path().join("Cargo.toml"), &original).unwrap();
        fs::create_dir(root.path().join("src")).unwrap();
        fs::write(root.path().join("src/lib.rs"), "").unwrap();
        let cache = root
            .path()
            .join("cargo-home/registry/index/index.crates.io-1949cf8c6b5b557f/.cache/de/mo");
        fs::create_dir_all(&cache).unwrap();
        fs::write(
            root.path()
                .join("cargo-home/registry/index/index.crates.io-1949cf8c6b5b557f/config.json"),
            r#"{"dl":"https://example.invalid/crates","api":"https://example.invalid"}"#,
        )
        .unwrap();
        let mut bytes = vec![3, 2, 0, 0, 0];
        bytes.extend_from_slice(b"etag: fixture\0");
        for version in ["1.0.0", "1.2.0", "2.0.0"] {
            let checksum = cached_crate(&root.path().join("cargo-home"), version);
            bytes.extend_from_slice(version.as_bytes());
            bytes.push(0);
            bytes.extend_from_slice(format!(r#"{{"name":"demo","vers":"{version}","deps":[],"cksum":"{checksum}","features":{{}},"yanked":false}}"#).as_bytes());
            bytes.push(0);
        }
        fs::write(cache.join("demo"), bytes).unwrap();
        Self { root, original }
    }

    fn seed_lockfile(&self) -> String {
        let archive =
            fs::read(self.path().join(
                "cargo-home/registry/cache/index.crates.io-1949cf8c6b5b557f/demo-1.0.0.crate",
            ))
            .unwrap();
        let checksum = checksum(&archive);
        let lock = format!(
            "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"demo\"\nversion = \"1.0.0\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\nchecksum = \"{checksum}\"\n\n[[package]]\nname = \"upgrade_cli_fixture\"\nversion = \"0.1.0\"\ndependencies = [\n \"demo\",\n]\n"
        );
        fs::write(self.path().join("Cargo.lock"), &lock).unwrap();
        lock
    }

    fn path(&self) -> &Path {
        self.root.path()
    }

    fn command(&self) -> Command {
        let mut command = Command::new(env!("CARGO_BIN_EXE_clippier"));
        // Isolate Cargo/configuration while retaining the installed toolchain for
        // the engine's offline lockfile-resolution subprocess.
        if let Some(rustup_home) = std::env::var_os("RUSTUP_HOME").or_else(|| {
            std::env::var_os("HOME").map(|home| {
                std::path::PathBuf::from(home)
                    .join(".rustup")
                    .into_os_string()
            })
        }) {
            command.env("RUSTUP_HOME", rustup_home);
        }
        command
            .current_dir(self.path())
            .env("CARGO_HOME", self.path().join("cargo-home"))
            .env("HOME", self.path())
            .env("CARGO_NET_OFFLINE", "true")
            .env(
                "CARGO_REGISTRIES_CRATES_IO_INDEX",
                "sparse+https://index.crates.io/",
            )
            .env("MOOSICBOX_STATE_DIR", self.path().join("state"))
            .env("MOOSICBOX_LOG_DIR", self.path().join("logs"))
            .stdin(Stdio::null());
        command
    }

    fn run(&self, args: &[&str]) -> Output {
        self.command().arg("upgrade").args(args).output().unwrap()
    }

    fn assert_unchanged(&self) {
        assert_eq!(
            fs::read_to_string(self.path().join("Cargo.toml")).unwrap(),
            self.original
        );
        assert!(!self.path().join("Cargo.lock").exists());
    }
}

fn report(output: &Output) -> Value {
    // from_slice rejects multiple JSON values and trailing non-whitespace diagnostics.
    let value: Value = serde_json::from_slice(&output.stdout)
        .unwrap_or_else(|error| panic!("{error}: {output:?}"));
    assert_eq!(value["schema_version"], 1);
    assert!(matches!(
        value["scope"].as_str(),
        Some("PLAN" | "CHECK" | "APPLY")
    ));
    value
}

#[test]
fn default_apply_refreshes_only_lockfile_when_requirement_is_current() {
    // >=1.0.0,<2 retains its spelling and already permits the selected 1.2.0.
    let fixture = Fixture::new(Some(">=1.0.0, <2"));
    let original_lock = fixture.seed_lockfile();
    let preview = fixture.run(&["plan", "--offline", "--output", "json"]);
    assert!(preview.status.success(), "{preview:?}");
    let summary = report(&preview);
    assert_eq!(summary["report"]["pending"], true);
    assert_eq!(summary["report"]["manifests"], serde_json::json!([]));
    assert_eq!(
        fs::read_to_string(fixture.path().join("Cargo.lock")).unwrap(),
        original_lock
    );
    assert_eq!(
        fs::read_to_string(fixture.path().join("Cargo.toml")).unwrap(),
        fixture.original
    );

    // A real offline Cargo resolution provides an exact preview without live writes.
    let exact = fixture.run(&[
        "plan",
        "--offline",
        "--resolve-lockfile",
        "--diff",
        "--output",
        "json",
    ]);
    assert!(exact.status.success(), "{exact:?}");
    let exact_report = report(&exact);
    assert_eq!(exact_report["report"]["lockfile"], "RESOLVED");
    assert!(exact_report["diff"].as_str().unwrap().contains("1.2.0"));
    assert_eq!(
        fs::read_to_string(fixture.path().join("Cargo.lock")).unwrap(),
        original_lock
    );
    assert_eq!(
        fs::read_to_string(fixture.path().join("Cargo.toml")).unwrap(),
        fixture.original
    );

    // Captured input/output is nonterminal; -y must bypass confirmation only.
    let applied = fixture.run(&["--offline", "-y", "--output", "json"]);
    assert!(applied.status.success(), "{applied:?}");
    let summary = report(&applied);
    assert_eq!(summary["outcome"], "APPLIED");
    assert_eq!(summary["report"]["lockfile"], "APPLIED");
    assert_eq!(summary["report"]["pending"], false);
    assert_eq!(
        fs::read_to_string(fixture.path().join("Cargo.toml")).unwrap(),
        fixture.original
    );
    let lock_text = fs::read_to_string(fixture.path().join("Cargo.lock")).unwrap();
    let lock: toml::Value = toml::from_str(&lock_text).unwrap();
    let demo = lock["package"]
        .as_array()
        .unwrap()
        .iter()
        .find(|package| package["name"].as_str() == Some("demo"))
        .unwrap();
    assert_eq!(demo["version"].as_str(), Some("1.2.0"));
    let archive = fs::read(
        fixture
            .path()
            .join("cargo-home/registry/cache/index.crates.io-1949cf8c6b5b557f/demo-1.2.0.crate"),
    )
    .unwrap();
    assert_eq!(demo["checksum"].as_str().unwrap(), checksum(&archive));
}

#[test]
fn no_lockfile_preserves_existing_lock_and_lockfile_only_preserves_manifest() {
    let fixture = Fixture::new(Some("1.0.0"));
    let original_lock = fixture.seed_lockfile();
    let preview = fixture.run(&["plan", "--offline", "--lockfile-only", "--output", "json"]);
    assert!(preview.status.success(), "{preview:?}");
    assert_eq!(
        report(&preview)["report"]["manifests"],
        serde_json::json!([])
    );
    assert_eq!(
        fs::read_to_string(fixture.path().join("Cargo.lock")).unwrap(),
        original_lock
    );
    assert_eq!(
        fs::read_to_string(fixture.path().join("Cargo.toml")).unwrap(),
        fixture.original
    );

    let applied = fixture.run(&["--offline", "--lockfile-only", "-y", "--output", "json"]);
    assert!(applied.status.success(), "{applied:?}");
    assert_eq!(report(&applied)["report"]["lockfile"], "APPLIED");
    assert_eq!(
        fs::read_to_string(fixture.path().join("Cargo.toml")).unwrap(),
        fixture.original
    );
    assert!(
        fs::read_to_string(fixture.path().join("Cargo.lock"))
            .unwrap()
            .contains("version = \"1.2.0\"")
    );

    // Reset only this fixture's lockfile, then allow manifest edits but no lock update.
    fs::write(fixture.path().join("Cargo.lock"), &original_lock).unwrap();
    let disabled = fixture.run(&["--offline", "--no-lockfile", "-y", "--output", "json"]);
    assert!(disabled.status.success(), "{disabled:?}");
    assert_eq!(report(&disabled)["report"]["lockfile"], "DISABLED");
    assert_eq!(
        fs::read_to_string(fixture.path().join("Cargo.lock")).unwrap(),
        original_lock
    );
    assert!(
        fs::read_to_string(fixture.path().join("Cargo.toml"))
            .unwrap()
            .contains("1.2.0")
    );
}

#[test]
fn plan_dry_run_and_check_are_read_only() {
    let fixture = Fixture::new(Some("1.0.0"));
    for args in [
        vec![
            "plan",
            "--offline",
            "--no-lockfile",
            "--output",
            "json",
            "--diff",
        ],
        vec![
            "--dry-run",
            "--offline",
            "--no-lockfile",
            "--output",
            "json",
            "--diff",
        ],
        vec![
            "--check",
            "--yes",
            "--offline",
            "--no-lockfile",
            "--output",
            "json",
            "--diff",
        ],
    ] {
        let output = fixture.run(&args);
        let summary = report(&output);
        assert_eq!(
            output.status.success(),
            !args.contains(&"--check"),
            "{output:?}"
        );
        assert_eq!(
            summary["outcome"],
            if args.contains(&"--check") {
                "CHECK_FAILED"
            } else {
                "PLANNED"
            }
        );
        assert_eq!(summary["report"]["applied"], false);
        assert!(summary["diff"].as_str().unwrap().contains("1.2.0"));
        fixture.assert_unchanged();
    }
}

